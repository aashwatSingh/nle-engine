/// A track fader at unity — the default, what an old project without the
/// field reads as, and what every caller constructing a `Track` by hand
/// wants. Public because `Track::gain_db` stopped being a bare `0.0` anyone
/// could write inline.
pub fn unity_gain() -> ParamTrack {
    ParamTrack::constant(crate::keyframe::ParamValue::Number(0.0))
}

/// Accepts either a bare number (schema v5 and earlier) or a full
/// `ParamTrack` (v6+). See `Track::gain_db` for why this compat can't live in
/// the migration chain.
fn deserialize_gain_db<'de, D>(deserializer: D) -> Result<ParamTrack, D::Error>
where
    D: serde::Deserializer<'de>,
{
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum GainDb {
        // Ordered with the scalar first: a v6 `ParamTrack` is a map and a v5
        // fader is a number, so the two can't be confused either way round,
        // but trying the cheap shape first keeps the common case cheap.
        Static(f64),
        Automated(ParamTrack),
    }
    Ok(match GainDb::deserialize(deserializer)? {
        GainDb::Static(db) => ParamTrack::constant(crate::keyframe::ParamValue::Number(db)),
        GainDb::Automated(track) => track,
    })
}

/// What a transition does between its two clips.
///
/// Kept as an enum rather than a generic effect because a transition takes
/// **two** inputs, which the single-input-per-clip effect chain can't express
/// at all — see `render::graph`'s `TransitionRender`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TransitionKind {
    /// The outgoing clip mixes directly into the incoming one.
    CrossDissolve,
    /// The outgoing clip dims to black over the first half, the incoming one
    /// brightens out of it over the second. It dims the clip's **colour** at
    /// full alpha rather than fading its alpha, so the track keeps covering
    /// whatever is on the tracks below for the whole transition — fading alpha
    /// instead looked right only on the bottom track and let lower tracks show
    /// through the dip everywhere else.
    DipToBlack,
    /// A hard-edged boundary sweeps left to right, revealing the incoming clip
    /// behind it. Unlike a dissolve, both clips are fully opaque at every
    /// point — the transition is *where* each one is drawn, not how
    /// transparent it is.
    ///
    /// Left-to-right only. Other directions (right-to-left, vertical,
    /// diagonal, barn-door) would each need a direction field on `Transition`,
    /// which is a schema change rather than a rendering one; deliberately not
    /// guessed at here.
    Wipe,
    /// The incoming clip slides in from the right over a stationary outgoing
    /// clip, fully opaque the whole way.
    ///
    /// Purely a position offset — no shader involvement at all, since
    /// `Transform2D::position` already places a clip wherever it needs to be.
    /// Like `Wipe`, one direction only, for the same reason.
    Slide,
}

impl TransitionKind {
    /// Every kind, for UI that offers a choice of transition. Exhaustive by
    /// construction: the `match` in `label` fails to compile if a variant is
    /// added without being handled, and a menu built from this array then
    /// picks it up for free — which is what stops a kind being implemented in
    /// the renderer but left unreachable in the editor.
    pub const ALL: [TransitionKind; 4] = [
        TransitionKind::CrossDissolve,
        TransitionKind::DipToBlack,
        TransitionKind::Wipe,
        TransitionKind::Slide,
    ];

    /// Human-readable name, as it should appear in a menu.
    pub fn label(self) -> &'static str {
        match self {
            TransitionKind::CrossDissolve => "Cross Dissolve",
            TransitionKind::DipToBlack => "Dip to Black",
            TransitionKind::Wipe => "Wipe",
            TransitionKind::Slide => "Slide",
        }
    }
}

/// A transition straddling one cut on one track.
///
/// Anchored to the cut (`at`) and centred on it, which is how an editor thinks
/// about it ("put a 1-second dissolve on this cut") and what keeps it attached
/// to the right edit when neighbouring clips are trimmed.
///
/// The transition region extends `duration / 2` either side of the cut, so both
/// clips are sampled **past their own trim points** during it — into their
/// handles, exactly like a real NLE. Where a clip has no handle material the
/// decoder holds its nearest frame instead of failing, so a dissolve on
/// footage trimmed to its very last frame degrades to a freeze rather than an
/// error.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Transition {
    pub id: TransitionId,
    pub kind: TransitionKind,
    /// The cut this straddles, in sequence time.
    pub at: TimeTick,
    /// Total length, centred on `at`.
    pub duration: TimeTick,
}

impl Transition {
    /// Half-open sequence-time range this transition affects.
    pub fn region(&self) -> (TimeTick, TimeTick) {
        let half = self.duration.0 / 2;
        (TimeTick(self.at.0 - half), TimeTick(self.at.0 - half + self.duration.0))
    }

    pub fn covers(&self, at: TimeTick) -> bool {
        let (start, end) = self.region();
        self.duration.0 > 0 && start <= at && at < end
    }

    /// How far through the transition `at` is, clamped to 0..=1.
    pub fn progress_at(&self, at: TimeTick) -> f32 {
        if self.duration.0 <= 0 {
            return 1.0;
        }
        let (start, _) = self.region();
        (((at.0 - start.0) as f64) / (self.duration.0 as f64)).clamp(0.0, 1.0) as f32
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Track {
    pub id: TrackId,
    pub kind: TrackKind,
    pub name: String,
    /// Invariant: sorted by `timeline_in`, non-overlapping. Enforced by edit
    /// ops (M3), checked by `invariants::check_no_overlaps` and the
    /// property-based test suite.
    pub clips: Vec<ClipInstance>,
    /// Transitions on this track's cuts. `serde(default)` so projects written
    /// before schema v3 still load — see `project::persist`'s migration chain.
    #[serde(default)]
    pub transitions: Vec<Transition>,
    /// Track fader, in dB, keyframeable. `0.0` is unity, which is why
    /// `serde(default)` is safe here — a project written before faders existed
    /// reads as every track at unity, i.e. exactly how it used to sound.
    ///
    /// **Was a plain `f64` through schema v5.** `deserialize_gain_db` reads
    /// either form, so a v5 project's bare number decodes as a constant track
    /// with no data loss. That compat lives in the deserializer rather than in
    /// `project::persist::migrate` for a structural reason: migration runs
    /// *after* decoding, and decoding a bare CBOR float into a `ParamTrack`
    /// fails before migration ever gets a chance to run. The rule that every
    /// format change needs a real migration is about old files still opening;
    /// for a field whose *type* changed, this is the only place that can be
    /// honoured.
    #[serde(default = "unity_gain", deserialize_with = "deserialize_gain_db")]
    pub gain_db: ParamTrack,
    /// Track pan, -1.0 (hard left) to 1.0 (hard right). `0.0` is centre.
    #[serde(default)]
    pub pan: f64,
    pub locked: bool,
    pub sync_locked: bool,
    pub muted: bool,
    pub solo: bool,
    pub height_px: u32,
}

impl Track {
    /// The transition active at `at`, if any. Transitions are anchored to
    /// distinct cuts, so at most one can cover a given tick in a well-formed
    /// project; the first match wins if that's ever violated.
    pub fn transition_at(&self, at: TimeTick) -> Option<&Transition> {
        self.transitions.iter().find(|t| t.covers(at))
    }

    /// The clip ending exactly at `cut` and the one starting there — the pair a
    /// transition anchored at `cut` bridges. `None` for either side when there
    /// is no clip there, which is how a transition at the head or tail of a
    /// clip becomes a plain fade in/out rather than an error.
    pub fn clips_at_cut(&self, cut: TimeTick) -> (Option<&ClipInstance>, Option<&ClipInstance>) {
        (
            self.clips.iter().find(|c| c.timeline_out == cut),
            self.clips.iter().find(|c| c.timeline_in == cut),
        )
    }
}

