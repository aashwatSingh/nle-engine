/// What a `ClipInstance` actually plays back. `NestedSequence` is spec 4.2's
/// "a sequence used as a clip inside another sequence" — the seam is here
/// from M0 even though multicam (which also nests) is deferred to v1.1.
///
/// No longer `Copy`/`Eq` since `Title` carries an owned `String` and `f64`s.
/// That's a deliberate trade: a title's appearance genuinely is part of what
/// the clip plays, and hiding it behind an id would mean inventing a
/// title-asset table that exists only to keep this enum two words wide.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum ClipSource {
    Media(MediaAssetId),
    NestedSequence(SequenceId),
    /// A text title, generated by the renderer rather than decoded from a
    /// file. It carries its whole appearance inline instead of referencing an
    /// asset because there is no file to reference — the clip *is* the source,
    /// which is also why editing the text is an ordinary project mutation and
    /// goes through undo like any other.
    Title(TitleSpec),
}

/// Where a line of title text sits relative to its anchor point.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum TextAlign {
    Left,
    Center,
    Right,
}

/// Everything needed to draw a title. Deliberately plain data with no handles
/// into a font cache or GPU state, so it serialises into the project file and
/// compares by value for undo coalescing like the rest of the model.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct TitleSpec {
    pub text: String,
    /// Family name resolved against installed system fonts at draw time. Not a
    /// path: a project that hardcoded `C:\Windows\Fonts\arial.ttf` would not
    /// open on another machine, whereas an unresolvable *family* can fall back
    /// to a default and still render something.
    pub font_family: String,
    pub size_px: f64,
    /// Rec.709-encoded RGBA in 0..1 — the values a colour picker hands you,
    /// matching how every decoded source arrives. The compositor linearises it
    /// on the way in like any other Rec.709 source, so a title and a clip of
    /// the same colour composite identically.
    pub color: [f64; 4],
    pub align: TextAlign,
    /// Anchor position as a fraction of the frame, (0,0) top-left to (1,1)
    /// bottom-right. `align` decides what the x component anchors (the left
    /// edge, centre, or right edge of the widest line); y is always the
    /// vertical centre of the whole text block, which is what makes a title
    /// stay put when a line is added to it.
    pub position: (f64, f64),
}

impl Default for TitleSpec {
    fn default() -> Self {
        TitleSpec {
            text: "Title".into(),
            font_family: "Arial".into(),
            size_px: 72.0,
            color: [1.0, 1.0, 1.0, 1.0],
            align: TextAlign::Center,
            position: (0.5, 0.5),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum SpeedCurve {
    /// e.g. 200% speed = Constant { numerator: 2, denominator: 1 }.
    Constant { numerator: i64, denominator: i64 },
    /// Keyframed rate; resolving timeline-tick -> source-tick under a
    /// non-constant curve is M7 (time remapping) work.
    Keyframed(ParamTrack),
}

impl SpeedCurve {
    /// Converts a timeline-tick delta into the corresponding source-tick
    /// delta. Exact for `Constant`.
    ///
    /// For `Keyframed` this returns the 1x (unmodified) delta: correctly
    /// integrating a keyframed rate curve to get elapsed source time is
    /// time-remapping (M7), and a wrong-but-plausible approximation here
    /// would silently desync audio against video. Returning 1x is at least
    /// a predictable, documented placeholder rather than a guess — every
    /// caller in `timeline` and `render` funnels through this one function,
    /// so M7 has exactly one place to fix.
    pub fn source_delta(&self, timeline_delta: i64) -> i64 {
        match self {
            SpeedCurve::Constant { numerator, denominator } if *denominator != 0 => {
                timeline_delta * numerator / denominator
            }
            _ => timeline_delta,
        }
    }
}

